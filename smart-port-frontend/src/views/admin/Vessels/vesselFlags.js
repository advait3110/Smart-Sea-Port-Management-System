const MID_LOOKUP = {};

MID_GROUPS.forEach(([code, name, mids]) => {
  mids.forEach((mid) => {
    MID_LOOKUP[String(mid)] = { code, name };
  });
});

/* { code, name } for a ship MMSI, or null when the MMSI is not a
   9-digit number with a known MID (for example a coast station,
   a beacon or a malformed value). `code` is null when the MID is
   shared by several territories. */
export const getVesselFlag = (mmsi) => {
  const digits = String(mmsi ?? "").trim();

  if (!/^\d{9}$/.test(digits)) return null;

  return MID_LOOKUP[digits.slice(0, 3)] || null;
};